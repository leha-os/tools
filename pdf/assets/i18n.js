let lehaLang = 'vi';
try { lehaLang = localStorage.getItem('leha_lang') || 'vi'; } catch (e) { lehaLang = 'vi'; }
if (lehaLang !== 'vi' && lehaLang !== 'en') lehaLang = 'vi';

/* Translate a key, with {param} interpolation. Falls back to English, then the key itself. */
function t(key, params) {
  const d = LANG[lehaLang] || LANG.vi;
  let s = d[key];
  if (s === undefined) s = LANG.en[key];
  if (s === undefined) return key;
  if (params) {
    for (const k in params) {
      if (Object.prototype.hasOwnProperty.call(params, k)) {
        s = s.split('{' + k + '}').join(String(params[k]));
      }
    }
  }
  return s;
}
function lehaGetLang() { return lehaLang; }
function lehaSaveLang(l) {
  if (l !== 'vi' && l !== 'en') return;
  lehaLang = l;
  try { localStorage.setItem('leha_lang', l); } catch (e) {}
}
